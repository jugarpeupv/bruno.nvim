local bru = require('bruno.parsers.bru')
local parsers = require('bruno.parsers')

local root = vim.fn.getcwd() .. '/tests/fixtures/bru-collection'

describe('parsers.bru', function()
  it('parses a request', function()
    local request = parsers.parse_request(root .. '/requests/simple.bru')
    eq('Simple Request', request.name)
    eq('http', request.type)
    eq('POST', request.method)
    eq('{{baseUrl}}/users/:id?foo=bar', request.url)
    eq('json', request.body.mode)
    match(request.body.content, '"hello": "world"')
    eq(3, #request.params)
    eq('search', request.params[1].name)
    eq(false, request.params[2].enabled)
    eq('key with spaces', request.params[3].name)
    eq(1, #request.path_params)
    eq('42', request.path_params[1].value)
    eq(3, #request.headers)
    eq(false, request.headers[2].enabled)
    eq('bearer', request.auth.mode)
    eq('{{token}}', request.auth.config.token)
    eq(1, #request.assertions)
    truthy(request.script.pre)
    truthy(request.script.post)
    truthy(request.tests)
    truthy(request.docs)
    eq(1, #request.vars.req)
    eq(1, #request.vars.res)
  end)

  it('parses OAuth2 configuration and additional parameters', function()
    local request = parsers.parse_request(root .. '/requests/oauth2.bru')
    eq('oauth2', request.auth.mode)
    local config = request.auth.config
    eq('authorization_code', config.grant_type)
    eq('client-id', config.client_id)
    eq('client-secret', config.client_secret)
    eq('http://127.0.0.1:53682/callback', config.callback_url)
    eq('https://example.com/authorize', config.authorization_url)
    eq('https://example.com/token', config.access_token_url)
    eq('read write', config.scope)
    eq(true, config.pkce)
    eq('body', config.credentials_placement)
    eq('credentials-id', config.credentials_id)
    eq('header', config.token_placement)
    eq('Bearer', config.token_header_prefix)
    eq(true, config.auto_fetch_token)
    eq(true, config.auto_refresh_token)
    eq('api', config.additional_params.authorization[1].value)
    eq('queryparams', config.additional_params.authorization[1].send_in)
    eq('resource-1', config.additional_params.token[1].value)
    eq('body', config.additional_params.token[1].send_in)
  end)

  it('parses environments and secrets', function()
    local env = parsers.load_environment(root, 'Local')
    eq('http://127.0.0.1:8765', env.baseUrl)
    eq('env-token', env.token)
    eq('', env.apiKey)
  end)

  it('parses collection variables', function()
    local vars = parsers.collection_vars(root)
    eq('collection-value', vars.collectionVar)
  end)

  it('lists only request files', function()
    local requests = parsers.list_requests(root)
    local paths = vim.tbl_map(function(item)
      return item.relpath
    end, requests)
    contains(paths, 'requests/simple.bru')
    contains(paths, 'requests/oauth2.bru')
    contains(paths, 'nested/inherit.bru')
    falsy(vim.tbl_contains(paths, 'folder.bru'))
    falsy(vim.tbl_contains(paths, 'collection.bru'))
  end)

  it('parses folder auth blocks', function()
    local auth = bru.parse_folder_auth(root .. '/folder.bru')
    truthy(auth)
    eq('bearer', auth.mode)
    eq('folder-token', auth.config.token)
  end)

  it('resolves inherited non-OAuth2 auth for display and cURL', function()
    local request = parsers.parse_request(root .. '/nested/inherit.bru')
    local auth = parsers.resolve_effective_auth(request)
    truthy(auth)
    eq('bearer', auth.mode)
    eq('folder-token', auth.config.token)
    eq(nil, parsers.resolve_auth(request))
  end)

  it('resolves OAuth2 auth inherited from a folder', function()
    local request = parsers.parse_request(root .. '/oauth-folder/inherit.bru')
    eq('inherit', request.auth.mode)
    local auth = parsers.resolve_auth(request)
    truthy(auth)
    eq('oauth2', auth.mode)
    eq('client_credentials', auth.config.grant_type)
    eq('folder-client', auth.config.client_id)
  end)

  it('parses disabled dictionary entries', function()
    local doc = bru.parse([[
headers {
  A: one
  ~B: two
}
]])
    local entries = doc.by_name.headers.entries
    eq(true, entries[1].enabled)
    eq(false, entries[2].enabled)
    eq('B', entries[2].name)
  end)
end)
